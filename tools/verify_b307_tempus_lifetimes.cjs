const path=require('path'),assert=require('node:assert/strict');
const {chromium}=require(process.env.ACME_PLAYWRIGHT_MODULE||'playwright');
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:process.env.ACME_CHROMIUM_EXECUTABLE,args:['--no-sandbox','--disable-dev-shm-usage']});
 const page=await browser.newPage(),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 page.on('dialog',async d=>d.accept());
 await page.goto('file://'+path.resolve('addons/acme_tempusls/ui/tempusls.html'));
 await page.waitForFunction(()=>window.TLS_VIEW&&typeof window.tls.therapy==='function');
 await page.evaluate(()=>{tls.mode('dialog');tls.power(true);});
 await page.waitForTimeout(100);
 const set=async state=>{
  await page.evaluate(state=>window.dispatchEvent(new CustomEvent('tempusLS:host',{detail:{raw:{type:'LOAD',state:{...TLS_VIEW.s,...state}}}})),state);
  await page.waitForTimeout(70);
 };
 await page.evaluate(()=>tls.therapy('patient-a:4',false));
 await set({phase:'charging',chargeStarted:performance.now()/1000,pads:true,ecg:true});
 await page.evaluate(()=>tls.therapy('patient-a:4',false));
 await page.waitForTimeout(70);
 assert.equal(await page.evaluate(()=>TLS_VIEW.s.phase),'charging','native polling cancelled charge before its browser handshake');
 await set({phase:'charged',charge:1,chargedAt:10000,pacing:true,current:80,syncPending:true});
 await page.evaluate(()=>tls.therapy('patient-a:4',true));
 await page.waitForTimeout(70);
 assert.equal(await page.evaluate(()=>TLS_VIEW.s.phase),'charged','valid native charge was cancelled');
 await page.evaluate(()=>tls.therapy('patient-b:4',false));
 await page.waitForTimeout(70);
 assert.deepEqual(await page.evaluate(()=>[TLS_VIEW.s.phase,TLS_VIEW.s.charge,TLS_VIEW.s.pacing,TLS_VIEW.s.current,TLS_VIEW.s.syncPending]),['idle',0,false,0,false],'patient change retained prior therapy');
 await set({phase:'charged',charge:1,chargedAt:10000});
 await page.evaluate(()=>tls.therapy('patient-b:4',false));
 await page.waitForTimeout(70);
 assert.equal(await page.evaluate(()=>TLS_VIEW.s.phase),'idle','expired native authorization remained charged in UI');
 await set({phase:'charged',charge:1,pacing:true,current:80});
 await page.evaluate(()=>tls.therapy('patient-b:5',false));
 await page.waitForTimeout(70);
 assert.deepEqual(await page.evaluate(()=>[TLS_VIEW.s.phase,TLS_VIEW.s.pacing]),['idle',false],'clinical reset retained therapy');
 assert.deepEqual(errors,[]);
 console.log('PASS LS native therapy identity, charge handshake, patient switch, expiry and clinical reset');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1);});
